// --- 4. the guard -----------------------------------------------------------

func s4(w *report.W, m *embed.Model, base baseline) {
	w.Section(4, "The fix: a veto that lives outside the similarity function")
	w.Expect(
		"Section 2 says a decisive token cannot dominate a pooled vector, so stop",
		"asking it to. Extract each query's decisive tokens and veto a hit when they",
		"disagree, regardless of cosine. The obvious definition of decisive is",
		"*high IDF*. The prediction was that an IDF cut would work. **It does not, and",
		"the reason is worth more than the fix.**",
	)

	w.Sub("Why an IDF cut cannot work here")
	hist := m.IDFHistogram()
	total := 0
	for _, n := range hist {
		total += n
	}
	rows := [][]string{}
	cum := 0
	for df := 1; df < len(hist) && df <= 8; df++ {
		cum += hist[df]
		rows = append(rows, []string{report.N(df), report.N(hist[df]),
			report.Pct(float64(hist[df]) / float64(total)),
			report.Pct(float64(cum) / float64(total))})
	}
	w.Table([]string{"document frequency", "vocabulary entries", "share", "cumulative"}, rows)
	pcts := [][]string{}
	for _, p := range []float64{0.10, 0.30, 0.50, 0.70, 0.90} {
		pcts = append(pcts, []string{report.Pct(p), report.F3(m.IDFPercentile(p))})
	}
	w.Table([]string{"IDF percentile", "value"}, pcts)
	w.Note(
		"Over 170 documents most of the vocabulary occurs once or twice, so the IDF",
		"distribution is a spike. Every percentile from the 10th to the 90th returns",
		"the same cut, which means *there is no IDF threshold to tune*: any setting",
		"admits nearly every content word - `but`, `cannot`, `answer` alongside",
		"`germany` and `401`. The decisive set then grows with sentence length, which",
		"reintroduces exactly the dilution the guard was built to escape. This is a",
		"corpus-size artefact, and it is also what every team hits when they compute",
		"IDF over their own small document set instead of a background corpus.",
	)

	w.Sub("Bound the size of the set instead")
	w.Note(
		"Take the K highest-IDF tokens of each query, however common they are. K is a",
		"budget, not a threshold, so it is insensitive to the shape of the IDF",
		"distribution and to sentence length. Two queries about different countries",
		"cannot agree on their top-K; two phrasings of the same question usually can.",
	)
	sweep := [][]string{}
	type cand struct {
		k     int
		j     float64
		res   armResult
		score float64
	}
	var best cand
	best.score = -1
	for _, k := range []int{1, 2, 3, 4} {
		for _, j := range []float64{0.34, 0.50, 0.67, 1.00} {
			cfg := armCfg(0.60, true, gateway.CoalesceOff)
			cfg.Cache.GuardTopK = k
			cfg.Cache.GuardJaccard = j
			r := runArm(fmt.Sprintf("K=%d J=%.2f", k, j), cfg, m, base.trap)
			sweep = append(sweep, []string{
				report.N(k), report.F3(j),
				report.Pct(r.st.HitRate()),
				report.Pct2(r.falseRate()),
				report.Pct(r.confusableErrRate()),
				report.N(r.st.GuardVetoes),
				report.N(r.st.Hits() - r.st.Wrong()),
			})
			// Correct answers served without a backend call: the quantity an
			// operator is actually buying. It refuses to let a policy win by
			// vetoing everything, and it refuses to let one win by serving
			// everything.
			score := float64(r.st.Hits() - r.st.Wrong())
			if score > best.score {
				best = cand{k, j, r, score}
			}
		}
	}
	w.Table([]string{"top-K", "min Jaccard", "hit rate", "false-hit (headline)",
		"error (confusable)", "vetoes", "correct answers served from cache"}, sweep)

	noGuard := runArm("no guard", armCfg(0.60, false, gateway.CoalesceOff), m, base.trap)
	w.Sub("Head to head at the same threshold, trap-heavy stream")
	w.Table(armHeader(), [][]string{noGuard.row(), best.res.row()})

	w.Sub("What the guard actually vetoed")
	w.Table([]string{"example query", "top-K decisive tokens"},
		guardExamples(m, best.k))

	w.Found(
		"The best setting is K="+report.N(best.k), "with Jaccard",
		report.F3(best.j)+". It takes the confusable error rate from",
		report.Pct(noGuard.confusableErrRate()), "to", report.Pct(best.res.confusableErrRate()),
		"and precision from", report.Pct(noGuard.st.Precision()), "to",
		report.Pct(best.res.st.Precision())+",",
		"while the hit rate moves from", report.Pct(noGuard.st.HitRate()), "to",
		report.Pct(best.res.st.HitRate())+".",
		"In absolute terms it serves", report.N(best.res.st.Hits()-best.res.st.Wrong()-(noGuard.st.Hits()-noGuard.st.Wrong())),
		"more CORRECT answers from cache than the unguarded configuration, which is the",
		"only comparison that is not gameable by moving the threshold.",
		"**The mechanism is not better similarity. It is a second signal that is",
		"insensitive to length, applied as a veto rather than as a term in an average.**",
		"That is the transferable idea: when one feature must be able to overrule a",
		"whole document, it cannot live inside a mean.",
	)

	guardPrice(w, m, noGuard, best.res, best.k, best.j)
}

// guardPrice is the section I did not plan to write.
//
// The sweep above prices the guard at about one point of hit rate, which reads
// as almost free. Writing the unit test for the guard produced a flatly
// contradictory number - it rejected most genuine paraphrases - and both
// measurements were correct. Reconciling them is the most useful thing in this
// report, because the reconciliation is the same error section 3 is about,
// committed a second time against the fix instead of the problem.
func guardPrice(w *report.W, m *embed.Model, noGuard, guarded armResult, k int, j float64) {
	w.Sub("The price the aggregate number hides")

	w.Expect(
		"A one-point drop in hit rate implies the veto almost never fires on traffic",
		"the cache would otherwise have served correctly. Prediction: measuring the",
		"veto directly on the population it exists to adjudicate - pairs of DIFFERENT",
		"wordings of the SAME question - will show a similarly small effect.",
		"**This prediction is wrong, and the aggregate is the reason.**",
	)

	ex, sem := noGuard.st.ExactHits, noGuard.st.SemanticHits
	w.Table([]string{"unguarded arm", "count", "share of hits"}, [][]string{
		{"verbatim repeats (exact key)", report.N(ex), report.Pct(ratio(float64(ex), float64(ex+sem)))},
		{"cross-wording (semantic)", report.N(sem), report.Pct(ratio(float64(sem), float64(ex+sem)))},
	})

	para, conf := populations()
	w.Line(fmt.Sprintf("Held-out populations from the labelled corpus: **%d paraphrase pairs** "+
		"(same intent, different wording - the cache MUST serve these) and **%d confusable "+
		"pairs** (same family, different intent - the cache MUST NOT). Each row stores the "+
		"first query and asks the second, so the guard is the only thing that varies.",
		len(para), len(conf)))
	w.Blank()

	type row struct {
		label      string
		kept, srvd float64
	}
	var rows []row
	rows = append(rows, row{"no guard", pairHitRate(m, armCfg(0.35, false, gateway.CoalesceOff).Cache, para),
		pairHitRate(m, armCfg(0.35, false, gateway.CoalesceOff).Cache, conf)})
	for _, kk := range []int{1, 2, 3, 4} {
		for _, jj := range []float64{0.20, 0.34, 0.50, 0.67, 1.00} {
			c := armCfg(0.35, true, gateway.CoalesceOff).Cache
			c.GuardTopK, c.GuardJaccard = kk, jj
			rows = append(rows, row{fmt.Sprintf("K=%d J=%.2f", kk, jj),
				pairHitRate(m, c, para), pairHitRate(m, c, conf)})
		}
	}
	var tbl [][]string
	for _, r := range rows {
		tbl = append(tbl, []string{r.label, report.Pct(r.kept), report.Pct(r.srvd)})
	}
	w.Table([]string{"guard", "paraphrases KEPT (want high)", "confusables SERVED (want low)"}, tbl)

	var base, chosen row
	for _, r := range rows {
		if r.label == "no guard" {
			base = r
		}
		if r.label == fmt.Sprintf("K=%d J=%.2f", k, j) {
			chosen = r
		}
	}
	lost := ratio(base.kept-chosen.kept, base.kept)

	w.Found(
		"On the population it actually adjudicates, the chosen guard rejects",
		report.Pct(lost), "of the genuine paraphrase hits it could have served",
		"("+report.Pct(base.kept), "kept without it,", report.Pct(chosen.kept), "with it),",
		"while taking confusables served from", report.Pct(base.srvd), "to",
		report.Pct(chosen.srvd)+".",
		"Both numbers are true. The aggregate hit rate barely moves because",
		report.Pct(ratio(float64(ex), float64(ex+sem))), "of cache hits in this workload are",
		"**verbatim repeats**, whose decisive sets are identical by construction and which",
		"the veto therefore passes for free. The guard is nearly invisible in aggregate",
		"precisely because it only touches the minority of traffic that the word",
		"*semantic* refers to.",
	)
	w.Note(
		"So the honest recommendation is narrower than the sweep suggests. If the value",
		"case for the cache is deduplicating repeated identical questions, the veto is",
		"close to free and should be on. If the value case is consolidating paraphrases -",
		"the reason anyone builds a semantic cache rather than a hash map - the veto",
		"removes roughly four out of five of the hits being paid for, and the aggregate",
		"dashboard will not show it. This is section 3's error committed against the fix:",
		"a number dominated by benign traffic, quoted as if it described the hard case.",
	)
	w.Note(
		"Two structural notes visible in the table. At K=1 the Jaccard parameter is inert:",
		"one token gives a Jaccard of 0 or 1, so every setting in (0,1] decides",
		"identically. And J does not mean the same thing at different K, because the",
		"union grows with K - which is why the sweep is not monotone in K at fixed J.",
		"The parameter with a stable meaning is *how many of the K tokens must agree*,",
		"not the ratio.",
	)
}

// populations splits the labelled corpus into the two sets the guard is a
// classifier over. Ground truth is used HERE, in the scoring, and never inside
// the cache - which is what internal/cache's scrambled-label test enforces.
func populations() (para, conf [][2]corpus.Query) {
	byIntent := map[string][]corpus.Query{}
	for _, q := range corpus.All() {
		byIntent[q.Intent] = append(byIntent[q.Intent], q)
	}
	for _, intent := range corpus.Intents() {
		qs := byIntent[intent]
		for i := 0; i+1 < len(qs); i++ {
			if qs[i].Tenant == qs[i+1].Tenant {
				para = append(para, [2]corpus.Query{qs[i], qs[i+1]})
			}
		}
	}
	all := corpus.All()
	for i, a := range all {
		for _, b := range all[i+1:] {
			if a.Tenant == b.Tenant && a.Intent != b.Intent &&
				corpus.ConfusableIntents(a.Intent, b.Intent) {
				conf = append(conf, [2]corpus.Query{a, b})
			}
		}
	}
	return para, conf
}

// pairHitRate stores the first query of each pair in a fresh cache and asks the
// second, so the only variable is the admission policy.
func pairHitRate(m *embed.Model, cfg cache.Config, pairs [][2]corpus.Query) float64 {
	hit := 0
	for _, p := range pairs {
		c := cache.New(m, cfg)
		e := cache.Entry{
			Text: p[0].Text, Tenant: p[0].Tenant, Intent: p[0].Intent,
			Answer: corpus.Answer(p[0].Intent), Vec: m.Embed(p[0].Text),
			Rare: c.DecisiveTokens(p[0].Text),
		}
		c.Put(e)
		if c.Lookup(p[1].Text, p[1].Tenant).Hit {
			hit++
		}
	}
	return ratio(float64(hit), float64(len(pairs)))
}

