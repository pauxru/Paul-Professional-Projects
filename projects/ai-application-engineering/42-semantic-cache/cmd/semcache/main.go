// crossTenantLeaks counts wrong answers on tenant-specific intents, and how
// many of those are the designed identical-wording trap.
func crossTenantLeaks(outs []gateway.Outcome, reqs []gateway.Request) (int, int) {
	leaks, trap := 0, 0
	for _, o := range outs {
		if o.Correct || corpus.Shared(o.TrueIntent) {
			continue
		}
		leaks++
		if corpus.Family(o.TrueIntent) == "tenant-plan" {
			trap++
		}
	}
	return leaks, trap
}

