func liveFlightDemo() string {
	var b strings.Builder
	g := flight.New()
	const herd = 32

	// Determinism here has to be built, not assumed. `Do` launches the leader's work
	// in a goroutine, so without a gate that goroutine races the loop below that is
	// still registering the other 31 subscribers -- and a follower counts as a LATE
	// joiner precisely when it arrives after the first chunk. The race is silent: it
	// changes only a number in a report, so it reads as a plausible result rather
	// than as a bug. It surfaced when the suite ran the report with GOMAXPROCS=8 left
	// over from the stress stage and late joiners went from 1 to 18.
	//
	// So: `herdReady` holds the leader before its first emit until the whole herd is
	// subscribed, and `started` holds the explicit late joiner until after it. Every
	// ordering the counters depend on is now a happens-before edge, not a scheduling
	// accident.
	herdReady := make(chan struct{})
	started := make(chan struct{})
	rest := make(chan struct{})
	work := func(ctx context.Context, emit flight.Emit) error {
		<-herdReady
		emit([]byte("the "))
		emit([]byte("refund "))
		close(started)
		<-rest
		emit([]byte("window "))
		emit([]byte("is "))
		emit([]byte("30 days"))
		return nil
	}

	subs := make([]*flight.Sub, herd)
	for i := range subs {
		subs[i], _ = g.Do(context.Background(), "same-question", work)
	}
	close(herdReady)
	<-started
	late, _ := g.Do(context.Background(), "same-question", work)
	close(rest)

	bodies := map[string]int{}
	for _, s := range append(subs, late) {
		body, _ := drain(s)
		bodies[body]++
		s.Close()
	}

	st := g.Stats()
	fmt.Fprintf(&b, "%d concurrent requests for the same question\n", herd+1)
	fmt.Fprintf(&b, "  backend calls            : %d\n", st.Calls)
	fmt.Fprintf(&b, "  leaders                  : %d\n", st.Leaders)
	fmt.Fprintf(&b, "  followers                : %d\n", st.Followers)
	fmt.Fprintf(&b, "  late joiners (mid-stream): %d\n", st.LateJoins)
	fmt.Fprintf(&b, "  distinct bodies received : %d\n", len(bodies))
	keys := make([]string, 0, len(bodies))
	for k := range bodies {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, body := range keys {
		fmt.Fprintf(&b, "    %2d x %q\n", bodies[body], body)
	}
	fmt.Fprintf(&b, "  leaders + followers == requests: %v\n",
		st.Leaders+st.Followers == herd+1)
	return b.String()
}

