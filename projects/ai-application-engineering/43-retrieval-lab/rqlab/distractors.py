def _identifier(rng: random.Random) -> str:
    return rng.choice(_IDENTIFIER_TEMPLATES).format(
        cn=rng.choice(_CODENAMES),
        err=rng.choice(_ERROR_STEMS),
        k=rng.randint(2, 41),
        num=rng.randint(1000, 9999),
    )


def _paragraph(rng: random.Random, topic: str) -> str:
    subject = rng.choice(_SUBJECTS[topic])
    parts = [
        f"{subject.capitalize()} {rng.choice(_VERB_PHRASES)}.",
        rng.choice(_TECHNICAL).format(n=rng.choice(_NUMBERS)),
        rng.choice(_OBSERVATIONS),
        _identifier(rng),
    ]
    if rng.random() < 0.35:
        parts.append(rng.choice(_CAVEATS))
    if rng.random() < 0.45:
        parts.append(_identifier(rng))
    rng.shuffle(parts)
    return " ".join(parts)


def build_distractors(count: int = 58, seed: int = 20240517) -> tuple[Document, ...]:
    rng = random.Random(seed)
    docs: list[Document] = []
    for i in range(count):
        topic = TOPICS[i % len(TOPICS)]
        title = (
            f"{rng.choice(_TITLE_HEAD[topic])} {rng.choice(_TITLE_TAIL)}"
        )
        doc_id = f"note-{topic}-{i:02d}"
        lines = [f"# {title}", ""]
        for _ in range(rng.randint(4, 7)):
            lines.append(f"## {rng.choice(_SUBJECTS[topic]).title()}")
            lines.append("")
            for _ in range(rng.randint(2, 4)):
                lines.append(_paragraph(rng, topic))
                lines.append("")
        docs.append(Document(doc_id, title, "distractor", "\n".join(lines)))
    return tuple(docs)


def assert_no_leaked_values(docs: tuple[Document, ...]) -> None:
    """No distractor may state a governed value.

    A distractor containing one would be an unlabelled correct answer. Every
    recall figure in the lab would then be understated by an unknown amount,
    and the understatement would differ per configuration, which is worse than
    a uniform bias because it is not cancelled by comparison.
    """
    values = {f.value for f in FACTS}
    for d in docs:
        for v in values:
            if v in d.text:
                raise AssertionError(
                    f"distractor {d.doc_id} contains governed value {v!r}"
                )
