"""Distractor documents: the 90% of a knowledge base that answers nothing.

A retrieval benchmark built only from documents that contain answers measures
almost nothing, because the top-k of a 40-chunk index is close to the whole
index. Real corpora are mostly near-misses -- pages that use every word of the
query and state no governed value.

These documents are generated by recombining templates under a fixed seed. They
are lexically realistic and syntactically repetitive, which is disclosed in
docs/known-limitations.md.

One invariant matters more than any other here, and is enforced by
``assert_no_leaked_values`` and by a test: **no distractor may contain any
governed value string.** If one did, it would be an unlabelled correct answer,
and every metric in the lab would be biased downwards by an unknown amount --
precisely the defect that motivated generating the corpus from facts in the
first place.
"""

